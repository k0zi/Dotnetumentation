using System.Text;
using Dotnetumentation.Core.Model;
using TypeKind = Dotnetumentation.Core.Model.TypeKind;

namespace Dotnetumentation.Core.Generators;

/// <summary>
/// <c>README.md</c> of the output folder: an overview of the project with the component and namespace diagrams
/// embedded as <c>plantuml</c> code blocks, and links to every other diagram.
/// </summary>
public sealed class MarkdownIndexGenerator : IDiagramGenerator
{
    public IEnumerable<GeneratedFile> Generate(GeneratorContext context)
    {
        var project = context.Project;
        var md = new StringBuilder();
        md.Append($"# {project.Name}\n\n");
        md.Append("Static documentation generated by Dotnetumentation from the source code.\n\n");
        md.Append($"- Assembly: `{project.AssemblyName}`\n");
        if (project.TargetFramework is not null)
            md.Append($"- Target framework: `{project.TargetFramework}`\n");
        md.Append($"- Types: {project.Types.Count}, namespaces: {project.Namespaces.Count()}\n\n");

        if (context.Diagrams.HasFlag(DiagramKinds.Component))
        {
            md.Append("## Components\n\n");
            md.Append($"[{DocumentationPaths.Components}]({DocumentationPaths.Components})\n\n");
            AppendDiagram(md, ComponentDiagramGenerator.Components(project));
            md.Append("## Namespaces\n\n");
            md.Append($"[{DocumentationPaths.Namespaces}]({DocumentationPaths.Namespaces})\n\n");
            AppendDiagram(md, ComponentDiagramGenerator.Namespaces(project));
        }

        md.Append("## Types\n\n");
        foreach (var group in project.Types.GroupBy(t => t.Namespace).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            md.Append($"### {DocumentationPaths.NamespaceTitle(group.Key)}\n\n");
            if (context.Diagrams.HasFlag(DiagramKinds.Class))
                md.Append($"Class diagram: [{DocumentationPaths.ClassDiagram(group.Key)}]({DocumentationPaths.ClassDiagram(group.Key)})\n\n");
            md.Append("| Type | Kind | Summary |\n|------|------|---------|\n");
            foreach (var type in group)
                md.Append($"| `{Cell(type.Name)}` | {Kind(type)} | {Cell(type.Summary ?? "")} |\n");
            md.Append('\n');
        }

        AppendMethodLinks(md, "Sequence diagrams",
            context.Sequences.Select(s => (s.Namespace, s.TypeName, s.MethodId, DocumentationPaths.Sequence(s.TypeName, s.Namespace, s.MethodId))));
        AppendMethodLinks(md, "Activity diagrams",
            context.Activities.Select(a => (a.Namespace, a.TypeName, a.MethodId, DocumentationPaths.Activity(a.TypeName, a.Namespace, a.MethodId))));

        yield return new GeneratedFile(DocumentationPaths.Index, md.ToString());
    }

    private static void AppendDiagram(StringBuilder md, string plantUml) =>
        md.Append("```plantuml\n").Append(plantUml).Append("```\n\n");

    private static void AppendMethodLinks(StringBuilder md, string title,
        IEnumerable<(string Namespace, string TypeName, string MethodId, string Path)> methods)
    {
        var list = methods.ToList();
        if (list.Count == 0)
            return;
        md.Append($"## {title}\n\n");
        foreach (var type in list.GroupBy(m => (m.Namespace, m.TypeName))
                     .OrderBy(g => g.Key.Namespace, StringComparer.Ordinal).ThenBy(g => g.Key.TypeName, StringComparer.Ordinal))
        {
            var fullName = type.Key.Namespace.Length == 0 ? type.Key.TypeName : $"{type.Key.Namespace}.{type.Key.TypeName}";
            md.Append($"- `{Cell(fullName)}`\n");
            foreach (var method in type.OrderBy(m => m.MethodId, StringComparer.Ordinal))
                md.Append($"  - [{Cell(method.MethodId)}]({method.Path})\n");
        }
        md.Append('\n');
    }

    private static string Kind(TypeModel type)
    {
        var kind = type.Kind switch
        {
            TypeKind.RecordStruct => "record struct",
            _ => type.Kind.ToString().ToLowerInvariant(),
        };
        if (type.IsStatic)
            return "static " + kind;
        if (type.IsAbstract && type.Kind != TypeKind.Interface)
            return "abstract " + kind;
        return kind;
    }

    private static string Cell(string text) => text.Replace("|", "\\|").Replace("\n", " ");
}
